// 8. Download / Inspect DDEX XML
app.get('/api/releases/:id/ddex', (req: Request, res: Response) => {
  const db = getDb();
  const release = db.releases.find((r) => r.id === req.params.id);

  if (!release) {
    return res.status(404).json({ success: false, error: 'Release not found' });
  }

  const xml = generateDdexXml(release);
  res.setHeader('Content-Type', 'application/xml');
  res.send(xml);
});

// 9. File upload: Audio
app.post('/api/upload/audio', upload.single('audio'), (req: Request, res: Response) => {
  if (!req.file) {
    return res.status(400).json({ success: false, error: 'No audio file uploaded' });
  }

  const fileUrl = `/uploads/${req.file.filename}`;

  // Analyze audio specs (simulated high resolution WAV analysis)
  const spec = {
    fileName: req.file.originalname,
    fileSizeBytes: req.file.size,
    format: req.file.originalname.toUpperCase().endsWith('.FLAC') ? 'FLAC' : 'WAV',
    sampleRateHz: 48000,
    bitDepth: 24,
    channels: 'Stereo',
    durationSeconds: 204, // 3:24
    peakLufs: -14.1,
    url: fileUrl,
  };

  res.json({
    success: true,
    fileUrl,
    spec,
    message: 'Audio master verified and validated (24-bit / 48kHz WAV, -14.1 LUFS).',
  });
});

