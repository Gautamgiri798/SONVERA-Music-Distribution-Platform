// 2. Get all releases
app.get('/api/releases', (req: Request, res: Response) => {
  const db = getDb();
  let results = [...db.releases];

  const { status, type, q } = req.query;

  if (status && status !== 'ALL') {
    results = results.filter((r) => r.status === status);
  }
  if (type && type !== 'ALL') {
    results = results.filter((r) => r.releaseType === type);
  }
  if (q && typeof q === 'string') {
    const term = q.toLowerCase();
    results = results.filter(
      (r) =>
        r.title?.toLowerCase().includes(term) ||
        r.primaryArtist?.toLowerCase().includes(term) ||
        r.upc?.includes(term)
    );
  }

  res.json({ success: true, count: results.length, data: results });
});

// 3. Get single release by ID
app.get('/api/releases/:id', (req: Request, res: Response) => {
  const db = getDb();
  const release = db.releases.find((r) => r.id === req.params.id);
  if (!release) {
    return res.status(404).json({ success: false, error: 'Release not found' });
  }
  res.json({ success: true, data: release });
});

// 4. Create new release
app.post('/api/releases', (req: Request, res: Response) => {
  const db = getDb();
  const newRelease = {
    ...req.body,
    id: req.body.id || `rel-${Date.now()}`,
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
    status: req.body.status || 'DRAFT',
    statusHistory: req.body.statusHistory || [
      {
        id: `sh-${Date.now()}`,
        status: 'DRAFT',
        timestamp: new Date().toISOString(),
        note: 'Release created in Release Center.',
        actor: req.body.primaryArtist || 'Artist',
      },
    ],
  };

  db.releases.unshift(newRelease);
  saveDb(db);

  res.status(201).json({ success: true, data: newRelease });
});

// 5. Update existing release
app.put('/api/releases/:id', (req: Request, res: Response) => {
  const db = getDb();
  const index = db.releases.findIndex((r) => r.id === req.params.id);

  if (index === -1) {
    return res.status(404).json({ success: false, error: 'Release not found' });
  }

  const updated = {
    ...db.releases[index],
    ...req.body,
    updatedAt: new Date().toISOString(),
  };

  db.releases[index] = updated;
  saveDb(db);

  res.json({ success: true, data: updated });
});

// 6. Submit release for distribution
app.post('/api/releases/:id/submit', (req: Request, res: Response) => {
  const db = getDb();
  const index = db.releases.findIndex((r) => r.id === req.params.id);

  if (index === -1) {
    return res.status(404).json({ success: false, error: 'Release not found' });
  }

  const targetDsps = req.body.dsps || db.releases[index].selectedDsps || [
    'spotify',
    'apple_music',
    'youtube_music',
    'amazon_music',
  ];

  const batchId = `BATCH-${Date.now().toString(36).toUpperCase()}-${Math.floor(1000 + Math.random() * 9000)}`;

  const updated = {
    ...db.releases[index],
    status: 'PROCESSING',
    submittedAt: new Date().toISOString(),
    statusHistory: [
      ...(db.releases[index].statusHistory || []),
      {
        id: `sh-sub-${Date.now()}`,
        status: 'SUBMITTED',
        timestamp: new Date().toISOString(),
        note: `Submitted for DDEX ERN 4.3 distribution to ${targetDsps.length} DSPs. Batch: ${batchId}`,
        actor: db.releases[index].primaryArtist,
        batchId,
      },
      {
        id: `sh-proc-${Date.now()}`,
        status: 'PROCESSING',
        timestamp: new Date().toISOString(),
        note: 'Ingestion pipeline converting DDEX feeds and packaging WAV audio packages.',
        actor: 'SONVÉRA Sandbox Hub',
      },
    ],
    deliveryStatuses: targetDsps.map((dspId: string) => ({
      dspId,
      dspName: dspId.replace('_', ' ').toUpperCase(),
      status: 'INGESTING',
      deliveryBatchId: batchId,
      deliveredAt: new Date().toISOString(),
    })),
    updatedAt: new Date().toISOString(),
  };

  db.releases[index] = updated;
  saveDb(db);

  res.json({
    success: true,
    batchId,
    status: 'PROCESSING',
    message: `Release successfully dispatched to ${targetDsps.length} partner streaming networks.`,
    data: updated,
  });
});

